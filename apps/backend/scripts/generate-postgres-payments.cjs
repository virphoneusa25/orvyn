// Keep payment behavior in the existing StripeStore; generate its async SQL boundary.
const ts=require('typescript'),fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const input=path.join(root,'src/billing/stripe.ts');
const output=path.join(root,'src/billing/PostgresStripeStore.ts');
const source=ts.createSourceFile(input,fs.readFileSync(input,'utf8').replace(/\r\n/g,'\n'),ts.ScriptTarget.Latest,true);
const original=source.statements.find(n=>ts.isClassDeclaration(n)&&n.name.text==='StripeStore');
const methods=new Set(original.members.filter(ts.isMethodDeclaration).map(n=>n.name.text));
const f=ts.factory,printer=ts.createPrinter({newLine:ts.NewLineKind.LineFeed});
const result=ts.transform(source,[context=>{
  function visit(node) {
    const updated=ts.visitEachChild(node,visit,context);
    if(ts.isCallExpression(updated)&&ts.isPropertyAccessExpression(updated.expression)) {
      const receiver=updated.expression.expression,name=updated.expression.name.text;
      if(receiver.kind===ts.SyntaxKind.ThisKeyword&&methods.has(name)||
        ['get','all','run'].includes(name)&&receiver.getText?.(source)?.includes('this.db'))
        return f.createParenthesizedExpression(f.createAwaitExpression(updated));
    }
    return updated;
  }
  return node=>{
    const members=[f.createConstructorDeclaration([f.createModifier(ts.SyntaxKind.PrivateKeyword)],[
      f.createParameterDeclaration([f.createModifier(ts.SyntaxKind.PrivateKeyword)],undefined,'db',undefined,f.createTypeReferenceNode('PostgresBillingDatabase')),
    ],f.createBlock([])),...original.members.filter(ts.isMethodDeclaration).map(method=>{
      const body=ts.visitNode(method.body,visit);
      const wrapped=f.createBlock([f.createReturnStatement(f.createCallExpression(
        f.createPropertyAccessExpression(f.createPropertyAccessExpression(f.createThis(),'db'),'transaction'),undefined,
        [f.createArrowFunction([f.createModifier(ts.SyntaxKind.AsyncKeyword)],undefined,[],undefined,f.createToken(ts.SyntaxKind.EqualsGreaterThanToken),body)]))],true);
      return f.updateMethodDeclaration(method,[...(method.modifiers||[]),f.createModifier(ts.SyntaxKind.AsyncKeyword)],method.asteriskToken,
        method.name,method.questionToken,method.typeParameters,method.parameters,
        method.type?f.createTypeReferenceNode('Promise',[method.type]):undefined,wrapped);
    })];
    const generated=f.updateClassDeclaration(original,original.modifiers,'PostgresStripeStore',undefined,
      [f.createHeritageClause(ts.SyntaxKind.ImplementsKeyword,[f.createExpressionWithTypeArguments(f.createIdentifier('AsyncPaymentContract'),undefined)])],members);
    const helper=ts.createSourceFile('helper.ts','class Helper { static fromDatabase(database:PostgresBillingDatabase):PostgresStripeStore {return new PostgresStripeStore(database);} }',ts.ScriptTarget.Latest,true);
    let text='// Generated by scripts/generate-postgres-payments.cjs from StripeStore; do not edit.\n'+
      'import {PostgresBillingDatabase} from "./PostgresBillingDatabase";\nimport type {StripeStore} from "./stripe";\n'+
      'type OriginalContract=Omit<StripeStore,"db">;\ntype AsyncPaymentContract={[K in keyof OriginalContract]:OriginalContract[K] extends (...args:infer A)=>infer R ? (...args:A)=>Promise<R>:never};\n'+printer.printNode(ts.EmitHint.Unspecified,generated,source);
    text=text.replace(/\}\s*$/,helper.statements[0].members.map(n=>printer.printNode(ts.EmitHint.Unspecified,n,helper)).join('\n')+'\n}\n');
    if(process.argv.includes('--check')) {
      if(!fs.existsSync(output)||fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==text)throw new Error('PostgresStripeStore is stale; run generate-postgres-payments.cjs');
    }else fs.writeFileSync(output,text);
    return node;
  };
}]);result.dispose();
